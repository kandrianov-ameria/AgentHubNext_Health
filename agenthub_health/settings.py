"""
Runtime settings, from three places (highest precedence first):

1. a real environment variable;
2. `.env` in the project root: the credentials only (gitignored, generated by
   `scripts/refresh_env.py`). A non-secret value set there also overrides
   suite.env on that PC;
3. `suite.env` in the project root: the environment name, base URLs, timeouts
   and other non-secret settings (committed to the repository).

Nothing here reads the agent-hub-backend repository - that is
`scripts/refresh_env.py`'s job, and it runs only when a credential has been
rotated.
"""
from __future__ import annotations

import os
from pathlib import Path

from dotenv import load_dotenv

PROJECT_ROOT = Path(__file__).resolve().parents[1]
ENV_FILE = PROJECT_ROOT / ".env"
SUITE_CONFIG_FILE = PROJECT_ROOT / "suite.env"
ASSETS_DIR = PROJECT_ROOT / "tests" / "assets"
RESULTS_DIR = PROJECT_ROOT / "results"
REPORT_FILE = RESULTS_DIR / "result.html"
# The remote configuration downloaded at the start of every run is saved here,
# one folder per environment, and used as the fallback when a later download fails.
# It holds live credentials (LLM provider keys, the Deepgram key, ProxyAuthHeader),
# so the folder is gitignored exactly like .env.
REMOTE_CONFIG_DIR = PROJECT_ROOT / "remote_config"
# One sub-folder per run: suite.log (what the suite did and how long it took),
# tests.log (one entry per check) and console.log (everything printed to the console).
LOGS_DIR = PROJECT_ROOT / "logs"

# override=False: a value already set wins, so the order of these calls is the
# precedence order (environment, then .env, then suite.env).
load_dotenv(ENV_FILE, override=False)
load_dotenv(SUITE_CONFIG_FILE, override=False)

# Base URLs the Windows build of AgentHubNext calls. Set in suite.env (taken from
# the agent-hub-backend constants; scripts/refresh_env.py keeps them current).
URL_VARS = [
    "AIHUB_SERVICE_BASE_URL",
    "MAV_STARKIT_BASE_URL",
    "TWO_D_TO_3D_BASE_URL",
    "TWO_D_TO_VIDEO_BASE_URL",
    "DEVICE_MAPPING_BASE_URL",
    "SEQ_BASE_URL",
]

# Credentials hardcoded in the Windows build. Set in .env only.
SECRET_VARS = [
    "AIHUB_WIN_TOKEN",
    "STARKIT_API_KEY",
    "AIHUB_DEVICE_MAPPING_TOKEN",
    "SEQ_API_KEY",
]

OPTIONAL_SECRET_VARS = ["TWO_D_TO_3D_BASIC_AUTH", "TWO_D_TO_VIDEO_BASIC_AUTH"]


# What to tell the user when a value is missing or wrong.
FIX_SECRET = "Run: .venv\\Scripts\\python scripts\\refresh_env.py"
FIX_SETTING = "Set it in suite.env in the project root (or restore that file from the repository)."


def fix_for(name: str) -> str:
    """Where a missing value belongs: credentials in .env, everything else in suite.env."""
    return FIX_SECRET if name in SECRET_VARS or name in OPTIONAL_SECRET_VARS else FIX_SETTING


def get(name: str, default: str = "") -> str:
    return (os.getenv(name) or default).strip()


def env_name() -> str:
    """DEV / QAS / STG / PRD. Agents and tools are filtered by this value."""
    return get("AGENTHUB_ENV", "QAS").upper()


def url(name: str) -> str:
    return get(name).rstrip("/")


# Defaults below apply only when suite.env does not set the value.
# Deepgram's public REST API (the Deepgram SDK in the app talks to it).
DEEPGRAM_API_URL = get("DEEPGRAM_API_URL", "https://api.deepgram.com").rstrip("/")
# Hardcoded in mcp-tavily-search-image/dist/index.js (tavilySearch).
TAVILY_SEARCH_URL = get("TAVILY_SEARCH_URL", "https://api.tavily.com/search")

# --- request timeouts (seconds) ---------------------------------------------
TIMEOUT_DEFAULT = float(get("AGENTHUB_HEALTH_TIMEOUT", "20"))
TIMEOUT_LLM = float(get("AGENTHUB_HEALTH_LLM_TIMEOUT", "60"))
TIMEOUT_GENERATION = float(get("AGENTHUB_HEALTH_GENERATION_TIMEOUT", "900"))

# The timeout AgentHubNext uses for every configuration download:
# RemoteConfigurationManager.CreateClient(20) and RemoteSettingsManager.DownloadAsync (20 s).
TIMEOUT_CONFIG = float(get("AGENTHUB_HEALTH_CONFIG_TIMEOUT", "20"))

# --- logs ------------------------------------------------------------------------
# How many run folders logs/ keeps; older ones are deleted at the start of a run.
LOG_RUNS_TO_KEEP = max(1, int(get("AGENTHUB_HEALTH_LOG_RUNS", "5")))
